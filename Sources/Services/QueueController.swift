import AppKit
import ApplicationServices
import CoreGraphics
import Carbon

/// Central app state: owns the queue, polls the pasteboard while queue mode is on,
/// and performs sequential / joined pastes into the frontmost app.
final class QueueController: ObservableObject {
    static let shared = QueueController()
    static let maxItems = 200
    static let maxItemBytes = 1_048_576

    @Published private(set) var items: [QueueItem] = QueueStorage.load() {
        didSet { QueueStorage.save(items) }
    }
    @Published private(set) var queueMode = false

    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var savedPasteboard: [[NSPasteboard.PasteboardType: Data]] = []
    private var explainedAccessibility = false
    private let defaults = UserDefaults.standard

    private init() {
        HotKeyManager.shared.handler = { [weak self] action in
            switch action {
            case .toggle: self?.toggleQueueMode()
            case .pasteNext: self?.pasteNext()
            }
        }
        HotKeyManager.shared.registerAll()
    }

    // MARK: - Settings

    private var isLIFO: Bool { defaults.string(forKey: "order") == "lifo" }
    private var autoAdvance: Bool { defaults.bool(forKey: "autoAdvance") }
    private var restoreClipboard: Bool { defaults.object(forKey: "restoreClipboard") as? Bool ?? true }
    private var delimiter: String {
        switch defaults.string(forKey: "delimiter") ?? "newline" {
        case "comma": return ", "
        case "tab": return "\t"
        case "space": return " "
        case "semicolon": return "; "
        default: return "\n"
        }
    }

    /// Index of the item the paste key will use next.
    var nextIndex: Int? { items.isEmpty ? nil : (isLIFO ? items.count - 1 : 0) }

    // MARK: - Queue mode

    func toggleQueueMode() { setQueueMode(!queueMode) }

    func setQueueMode(_ on: Bool) {
        guard on != queueMode else { return }
        if on {
            savedPasteboard = snapshotPasteboard()
            lastChangeCount = NSPasteboard.general.changeCount
            let t = Timer(timeInterval: 0.3, repeats: true) { [weak self] _ in self?.poll() }
            RunLoop.main.add(t, forMode: .common)
            timer = t
            queueMode = true
            HUD.shared.show("Queue mode on")
        } else {
            timer?.invalidate()
            timer = nil
            queueMode = false
            if !items.isEmpty && !askKeepRemaining() { items.removeAll() }
            HUD.shared.show("Queue mode off", symbol: "square.stack.3d.down.forward")
        }
    }

    private func askKeepRemaining() -> Bool {
        NSApp.activate(ignoringOtherApps: true)
        let alert = NSAlert()
        alert.messageText = "Queue mode turned off"
        alert.informativeText = "\(items.count) item(s) are still in the queue. Keep them for later or discard them?"
        alert.addButton(withTitle: "Keep")
        alert.addButton(withTitle: "Discard")
        return alert.runModal() == .alertFirstButtonReturn
    }

    // MARK: - Capturing

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        let types = Set(pb.types ?? [])
        let skip: Set<NSPasteboard.PasteboardType> = [.init("org.nspasteboard.ConcealedType"),
                                                       .init("org.nspasteboard.TransientType"),
                                                       .init("org.nspasteboard.AutoGeneratedType")]
        guard types.isDisjoint(with: skip), let item = capture(from: pb) else { return }
        guard items.count < Self.maxItems else {
            HUD.shared.show("Queue is full (\(Self.maxItems))", symbol: "exclamationmark.triangle")
            return
        }
        items.append(item)
        HUD.shared.show("Added \(items.count)", symbol: "plus.square.on.square")
    }

    private func capture(from pb: NSPasteboard) -> QueueItem? {
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return QueueItem(kind: .files, paths: urls.map(\.path))
        }
        if let text = pb.string(forType: .string), !text.isEmpty {
            return text.utf8.count <= Self.maxItemBytes ? QueueItem(kind: .text, text: text) : tooLarge()
        }
        if let data = pb.data(forType: .tiff) ?? pb.data(forType: .png).flatMap({ NSImage(data: $0)?.tiffRepresentation }) {
            return data.count <= Self.maxItemBytes ? QueueItem(kind: .image, imageData: data) : tooLarge()
        }
        return nil
    }

    private func tooLarge() -> QueueItem? {
        HUD.shared.show("Skipped: item larger than 1 MB", symbol: "exclamationmark.triangle")
        return nil
    }

    // MARK: - Editing

    func move(from source: IndexSet, to destination: Int) { items.move(fromOffsets: source, toOffset: destination) }
    func remove(_ item: QueueItem) { items.removeAll { $0.id == item.id } }
    func clear() { items.removeAll(); HUD.shared.show("Queue cleared", symbol: "trash") }

    // MARK: - Pasting

    func pasteNext() {
        guard let index = nextIndex else {
            NSSound.beep()
            HUD.shared.show("Queue is empty", symbol: "tray")
            return
        }
        let item = items.remove(at: index)
        writeToPasteboard(item)
        guard ensureAccessibility() else {
            HUD.shared.show("Copied — press ⌘V to paste, \(items.count) left", symbol: "keyboard")
            return
        }
        postKey(CGKeyCode(kVK_ANSI_V), flags: .maskCommand, after: 0.05)
        if autoAdvance { postKey(CGKeyCode(kVK_Tab), flags: [], after: 0.2) }
        HUD.shared.show("Pasted, \(items.count) left", symbol: "doc.on.clipboard")
        restoreIfFinished()
    }

    func pasteAllJoined() {
        let joinable = items.filter { $0.joinableText != nil }
        guard !joinable.isEmpty else {
            NSSound.beep()
            HUD.shared.show(items.isEmpty ? "Queue is empty" : "Nothing to join (images are excluded)", symbol: "tray")
            return
        }
        let ordered = isLIFO ? joinable.reversed() : joinable
        let text = ordered.compactMap(\.joinableText).joined(separator: delimiter)
        let ids = Set(joinable.map(\.id))
        items.removeAll { ids.contains($0.id) }
        writeToPasteboard(QueueItem(kind: .text, text: text))
        guard ensureAccessibility() else {
            HUD.shared.show("Copied \(joinable.count) joined — press ⌘V", symbol: "keyboard")
            return
        }
        // Give the menu bar window time to close so the previous app is frontmost again.
        postKey(CGKeyCode(kVK_ANSI_V), flags: .maskCommand, after: 0.35)
        HUD.shared.show("Pasted \(joinable.count) joined", symbol: "doc.on.clipboard")
        restoreIfFinished()
    }

    private func writeToPasteboard(_ item: QueueItem) {
        let pb = NSPasteboard.general
        item.write(to: pb)
        lastChangeCount = pb.changeCount // never capture our own writes
    }

    private func postKey(_ key: CGKeyCode, flags: CGEventFlags, after delay: TimeInterval) {
        DispatchQueue.main.asyncAfter(deadline: .now() + delay) {
            let source = CGEventSource(stateID: .hidSystemState)
            for down in [true, false] {
                guard let event = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: down) else { continue }
                event.flags = flags
                event.post(tap: .cghidEventTap)
            }
        }
    }

    private func restoreIfFinished() {
        guard items.isEmpty, restoreClipboard, !savedPasteboard.isEmpty else { return }
        let saved = savedPasteboard
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.8) { [weak self] in
            guard let self, self.items.isEmpty else { return }
            let pb = NSPasteboard.general
            pb.clearContents()
            pb.writeObjects(saved.map { entry -> NSPasteboardItem in
                let item = NSPasteboardItem()
                for (type, data) in entry { item.setData(data, forType: type) }
                return item
            })
            self.lastChangeCount = pb.changeCount
        }
    }

    private func snapshotPasteboard() -> [[NSPasteboard.PasteboardType: Data]] {
        (NSPasteboard.general.pasteboardItems ?? []).map { item in
            var entry: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types { entry[type] = item.data(forType: type) }
            return entry
        }
    }

    // MARK: - Accessibility

    /// Returns true if we may post keystrokes; otherwise explains why once and triggers the system prompt.
    func ensureAccessibility() -> Bool {
        if AXIsProcessTrusted() { return true }
        guard !explainedAccessibility else { return false }
        explainedAccessibility = true
        NSApp.activate(ignoringOtherApps: true)
        let alert = NSAlert()
        alert.messageText = "Allow PasteStackQueue to paste for you"
        alert.informativeText = """
        To paste queued items automatically, PasteStackQueue sends a ⌘V keystroke to the frontmost app. \
        macOS requires Accessibility permission for that.

        Until it is granted, the paste key still puts the next item on the clipboard and you press ⌘V yourself. \
        Enable it in System Settings › Privacy & Security › Accessibility.
        """
        alert.addButton(withTitle: "Grant Access…")
        alert.addButton(withTitle: "Not Now")
        if alert.runModal() == .alertFirstButtonReturn {
            let options = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
            _ = AXIsProcessTrustedWithOptions(options)
        }
        return false
    }
}
